function trackPage(tr) {
  const list = tasks.filter((t) => t.track === tr.key);
  if (!list.length) return '';
  let rows = '';
  let curEpic = null;
  for (const t of list) {
    if (t.epic !== curEpic) {
      curEpic = t.epic;
      rows += `<tr class="epicrow"><td colspan="7">${esc(EPIC[curEpic])} — إجمالي ${epicHrs(curEpic)} ساعة</td></tr>`;
    }
    rows += `<tr>
      <td class="idc">${t.id}</td>
      <td><b>${esc(t.title)}</b></td>
      <td><span class="cat ${CAT[t.cat].cls}">${CAT[t.cat].ar}</span></td>
      <td>${esc(t.desc)}</td>
      <td class="idc">${t.deps === '—' ? '—' : esc(t.deps)}</td>
      <td><span class="st ${ST[t.status].cls}">${ST[t.status].ar}</span></td>
      <td class="hrs">${t.hrs}</td>
    </tr>`;
  }
  return `
<section class="page">
  <div class="head"><h2>سجل المهام — ${esc(tr.name)}</h2><p>إجمالي المسار: ${sum(list)} ساعة · ${list.length} مهمة</p></div>
  <table class="tasktbl">
    <colgroup><col style="width:8%"><col style="width:15%"><col style="width:14%"><col style="width:35%"><col style="width:9%"><col style="width:9%"><col style="width:10%"></colgroup>
    <thead><tr><th>المعرّف</th><th>المهمة</th><th>الفئة</th><th>الوصف التفصيلي</th><th>يعتمد على</th><th>الحالة</th><th>ساعات</th></tr></thead>
    <tbody>${rows}</tbody>
  </table>
</section>`;
}

